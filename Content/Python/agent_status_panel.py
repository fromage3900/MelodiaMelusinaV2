import unreal
from pathlib import Path
import json

AGENT_MEMORY_DIR = Path(__file__).resolve().parent.parent / "Saved" / "AgentMemory"

# Agent status icons/colors
AGENT_ICONS = {
    "geometry": "🏛️",
    "material": "🎨",
    "placement": "📍",
    "integration": "🔗",
    "qa": "🛡️",
}

AGENT_COLORS = {
    "geometry": unreal.LinearColor.GREEN,
    "material": unreal.LinearColor.YELLOW,
    "placement": unreal.LinearColor.BLUE,
    "integration": unreal.LinearColor.CYAN,
    "qa": unreal.LinearColor.MAGENTA,
}


def get_agent_status_markdown() -> str:
    """Generate markdown status for all agents."""
    loop_files = {
        "geometry": Path(__file__).resolve().parent.parent / "deploy" / "SURREAL_ARCH_LOOP_STOP",
        "material": Path(__file__).resolve().parent.parent / "deploy" / "MATERIAL_AAA_LOOP.pid",
        "placement": Path(__file__).resolve().parent.parent / "deploy" / "SDF_FACTORY_LOOP.pid",
        "integration": Path(__file__).resolve().parent.parent / "deploy" / "SURREAL_WORLD_LOOP_STOP",
        "qa": Path(__file__).resolve().parent.parent / "Saved" / "Audit" / "hermes_health.json",
    }
    
    lines = ["# Agent Status Report", ""]
    
    for agent, icon in AGENT_ICONS.items():
        loop_stop = loop_files.get(agent)
        if loop_stop and loop_stop.exists():
            status = "🔴 STOPPED"
            if agent == "qa":
                try:
                    health = json.loads(loop_stop.read_text())
                    blessings_count = health.get("blessings", {}).get("blessings_count", 0)
                    status = f"🟢 {blessings_count} blessings healthy"
                except Exception:
                    status = "🔴 HEALTH ERROR"
        else:
            status = "🟢 RUNNING"
        
        lines.append(f"{icon} **{agent.title()} Agent**: {status}")
    
    lines.append("")
    lines.append("---")
    lines.append("*Generated by Agent Bridge MCP*")
    
    return "\n".join(lines)


def log_agent_status() -> None:
    """Log agent status to UE output log."""
    unreal.log("=" * 50)
    unreal.log("[AgentBridge] Agent Status:")
    
    for agent, icon in AGENT_ICONS.items():
        loop_files = {
            "geometry": Path(__file__).resolve().parent.parent / "deploy" / "SURREAL_ARCH_LOOP_STOP",
            "material": Path(__file__).resolve().parent.parent / "deploy" / "MATERIAL_AAA_LOOP.pid",
            "placement": Path(__file__).resolve().parent.parent / "deploy" / "SDF_FACTORY_LOOP.pid",
            "integration": Path(__file__).resolve().parent.parent / "deploy" / "SURREAL_WORLD_LOOP_STOP",
            "qa": Path(__file__).resolve().parent.parent / "Saved" / "Audit" / "hermes_health.json",
        }
        
        loop_stop = loop_files.get(agent)
        if loop_stop and loop_stop.exists():
            status = "STOPPED"
            if agent == "qa":
                try:
                    health = json.loads(loop_stop.read_text())
                    blessings_count = health.get("blessings", {}).get("blessings_count", 0)
                    status = f"{blessings_count} blessings"
                except Exception:
                    status = "ERROR"
        else:
            status = "READY"
        
        unreal.log(f"  [{agent[:2].upper()}] {icon} {agent.title()}: {status}")
    
    unreal.log("=" * 50)


