def register_agent_panel():
    """Register agent status in UE editor (called from init_unreal.py)."""
    log_agent_status()
    
    # Add to LiveLink menu for quick access
    menus = unreal.ToolMenus.get()
    live = menus.find_menu("LevelEditor.MainMenu.LiveLink")
    
    if live:
        # Add Agent Status entry
        entry = unreal.ToolMenuEntry(
            name="AgentBridgeStatus",
            type=unreal.MultiBlockType.MENU_ENTRY,
            user_interface_object_version=unreal.VersionedActionBase.VersionedAction
        )
        entry.set_label("Agent Bridge Status")
        
        # Python command to show status
        py_cmd = (
            "import agent_status_panel; "
            "agent_status_panel.log_agent_status(); "
            "unreal.log('[AgentBridge] Full status logged above')"
        )
        entry.set_string_command(
            type=unreal.ToolMenuStringCommandType.PYTHON,
            custom_type_name="",
            string=py_cmd
        )
        
        live.add_menu_entry("Portfolio", entry)
        menus.refresh_all_widgets()
        unreal.log("[AgentBridge] Agent status panel registered in LiveLink menu")
    
    return True


