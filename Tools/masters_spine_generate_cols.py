"""Generate a proving-preset COLS entry from a masters_spine_proving_probe JSON.

Plain Python (no editor needed):
    python Tools/masters_spine_generate_cols.py M_Master_Toon_Universal [tag]

Reads Saved/Audit/MastersSpine_20261028/proving_probe_<key>.json and writes/updates
Tools/masters_spine_cols_generated.py, whose GENERATED_COLS dict is merged into COLS
by Tools/masters_spine_proving_presets.py.

Value policy (deterministic, distinguishable, safe):
- scalar: 30% of the slider range when present; else default*1.2 (>1) or
  min(1.0, default*1.25 + 0.05); 4-decimal rounding.
- vector: default shifted +0.08 R / -0.05 G / +0.04 B, clamped 0..1, alpha 1.0.
- texture: engine placeholder paths (/Engine/) are replaced with the project
  T_Noise_White; real project textures are left inherited (no-op overrides avoided).
- groups are keyed by their numbered group string ("41 | Audio React"); the number
  becomes the MI index and the label becomes the slug.
Re-running reproduces the same table.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUTDIR = os.path.join(ROOT, "Saved", "Audit", "MastersSpine_20261028")
GEN = os.path.join(HERE, "masters_spine_cols_generated.py")
PROJECT_TEX = "/Game/EnvSandbox/Materials/Textures/T_Noise_White"
OUT_DIR = "/Game/EnvSandbox/Materials/Instances/Proving"


def slugify(text):
    parts = re.findall(r"[A-Za-z0-9]+", text or "")
    return "".join(p[:1].upper() + p[1:] for p in parts) or "Column"


def build_entry(key, tag):
    probe_path = os.path.join(OUTDIR, "proving_probe_%s.json" % key)
    if not os.path.isfile(probe_path):
        print("NO_PROBE", probe_path)
        sys.exit(1)
    with open(probe_path) as fh:
        probe = json.load(fh)
    rows = probe.get("master_rows", {}).get("params", [])
    master_path = probe.get("master_rows", {}).get("path")
    if not master_path:
        print("NO_MASTER_PATH in probe")
        sys.exit(1)

    groups = {}
    for p in rows:
        groups.setdefault(str(p.get("group") or ""), []).append(p)

    columns = []
    for group_name in sorted(groups):
        m = re.match(r"\s*(\d+)\s*\|\s*(.+)", group_name)
        index = int(m.group(1)) if m else len(columns) + 1
        label = m.group(2) if m else (group_name or "Column")
        if index >= 98:
            continue  # global/collection-only and legacy/diagnostic groups are not authoring surface
        overrides = {}
        for p in groups[group_name]:
            cls = p.get("c", "")
            name = p.get("parameter_name")
            if not name:
                continue
            if cls == "ScalarParameter":
                lo, hi, default = p.get("slider_min"), p.get("slider_max"), p.get("default_value")
                if lo is not None and hi is not None and float(hi) > float(lo):
                    value = float(lo) + 0.3 * (float(hi) - float(lo))
                elif default is not None:
                    d = float(default)
                    value = d * 1.2 if d > 1.0 else min(1.0, d * 1.25 + 0.05)
                else:
                    value = 1.0
                overrides[name] = {"s": round(value, 4)}
            elif cls == "VectorParameter" and p.get("rgb"):
                rgb = list(p["rgb"])[:4] + [1.0] * (4 - len(p.get("rgb", [])))
                r, g, b = rgb[0], rgb[1], rgb[2]
                overrides[name] = {"v": [
                    round(min(1.0, max(0.0, r + 0.08)), 4),
                    round(min(1.0, max(0.0, g - 0.05)), 4),
                    round(min(1.0, max(0.0, b + 0.04)), 4),
                    1.0,
                ]}
            elif "Texture" in cls and p.get("tex") and "/Engine/" in str(p.get("tex")):
                overrides[name] = {"t": PROJECT_TEX}
        if overrides:
            columns.append({"n": index, "slug": slugify(label), "ov": overrides})

    return {"master": master_path, "out_dir": OUT_DIR, "tag": tag, "columns": columns}


def main():
    key = sys.argv[1] if len(sys.argv) > 1 else "M_Master_Toon_Universal"
    tag = sys.argv[2] if len(sys.argv) > 2 else "Uni"
    entry = build_entry(key, tag)

    existing = {}
    if os.path.isfile(GEN):
        namespace = {}
        with open(GEN) as fh:
            exec(fh.read(), namespace)  # our own generated module
        existing = namespace.get("GENERATED_COLS", {})
    existing[key] = entry
    with open(GEN, "w") as fh:
        fh.write('"""Generated by Tools/masters_spine_generate_cols.py - do not hand-edit."""\n')
        fh.write("GENERATED_COLS = " + json.dumps(existing, indent=1, sort_keys=True) + "\n")
    gen_json = GEN.replace(".py", ".json")
    with open(gen_json, "w") as fh:
        json.dump(existing, fh, indent=1, sort_keys=True)
    print("WROTE", GEN)
    print("WROTE", gen_json)
    print("MASTER", key, "| tag", tag, "| columns", len(entry["columns"]))
    for col in entry["columns"]:
        print("  COL", col["n"], col["slug"], "| overrides", len(col["ov"]))


main()
