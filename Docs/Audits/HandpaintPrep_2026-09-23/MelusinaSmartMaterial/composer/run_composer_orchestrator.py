#!/usr/bin/env python
"""Drive the Mr. Sheep Composer job inside Substance 3D Painter by wire.

Run locally:  python run_composer_orchestrator.py
Prereq: Painter open with --enable-remote-scripting; composer_params.json
already generated by melodia_composer.py.

Sequence: wait for server -> ensure project -> JS bake -> poll -> composer
job (stack + variants + exports + save) -> report.

Melodia / Melusina only. No Grok*.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from painter_remote import PainterError, RemotePainter  # noqa: E402

SMS = os.path.abspath(os.path.join(HERE, ".."))
RUNNER = os.path.join(SMS, "composer", "painter_composer_run.py")

BAKE_CONFIGURE = '''(function() {
    var activeTS = alg.texturesets.getActiveTextureSet()[0];
    var params = alg.baking.textureSetBakingParameters(activeTS);
    params.materialParameters.commonParameters.Output_Size = [11, 11];
    params.materialParameters.detailParameters.Max_Frontal_Distance = 0.5;
    params.materialParameters.detailParameters.Max_Rear_Distance = 0.5;
    params.definitions.Normal.enabled = true;
    params.definitions.Ambient_occlusion.enabled = true;
    params.definitions.Curvature.enabled = true;
    params.definitions.Height.enabled = false;
    params.definitions.Position.enabled = false;
    params.definitions.Thickness.enabled = false;
    alg.baking.setTextureSetBakingParameters(activeTS, params);
    return { status: "configured", textureSet: activeTS };
})()'''

BAKE_TRIGGER = '''(function() {
    var activeTS = alg.texturesets.getActiveTextureSet()[0];
    alg.baking.bake(activeTS);
    return { status: "bake_triggered", textureSet: activeTS };
})()'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mesh", default=r"C:\EnvironmentPortfolio\BS_GodFile\Content\Melodia\Companions\ChoralSheep\choralsheep_vcol_melodia.fbx")
    ap.add_argument("--composer", default=os.path.join(HERE, "out", "composer_params.json"))
    ap.add_argument("--exports", default=os.path.join(SMS, "exports", "MrSheep", "variants"))
    ap.add_argument("--project", default=os.path.join(SMS, "exports", "MrSheep", "MrSheep_SMS.spp"))
    ap.add_argument("--log", default=os.path.join(HERE, "out", "painter_run.log"))
    ap.add_argument("--skip-bake", action="store_true")
    ap.add_argument("--skip-project", action="store_true")
    args = ap.parse_args()

    if not os.path.isfile(args.composer):
        raise SystemExit("composer params missing: %s (run melodia_composer.py first)"
                         % args.composer)

    rp = RemotePainter()
    print("waiting for Painter remote server on :60041 ...")
    if not rp.wait_ready(timeout=600):
        raise SystemExit("remote server never came up - is Painter running "
                         "with --enable-remote-scripting?")
    print("connected.")

    try:
        print("mesh currently open:", rp.exec_js(
            "alg.project.lastImportedMeshUrl()").strip()[:300])
    except PainterError as e:
        print("mesh probe failed:", str(e)[:200])

    def run_file_run(extra: str, label: str):
        # Painter executes injected code inside a function wrapper: names
        # created by a bare exec() land in locals, so functions defined in
        # the injected file cannot resolve them (NameError at call time).
        # Always exec into an explicit dict G and call G['fn'](...).
        script = ("G = {}\n"
                  "exec(compile(open(r'%s', encoding='utf-8').read(), "
                  "r'%s', 'exec'), G)\n%s" % (RUNNER, RUNNER, extra))
        print(">>", label)
        t0 = time.time()
        try:
            out = rp.exec_python(script)
            print("   done in %.1fs" % (time.time() - t0))
            return out
        except PainterError as e:
            print("   ERROR after %.1fs: %s" % (time.time() - t0, str(e)[:1500]))
            return None

    if not args.skip_project:
        run_file_run(
            "G['ensure_project'](r'%s', 2048, r'%s')" % (args.mesh, args.log),
            "ensure_project (scripted create)")

    # wait for an open project in edition state (owner-opened is the norm)
    t0 = time.time()
    ready = False
    while time.time() - t0 < 300:
        try:
            opn = rp.exec_js("alg.project.isOpen()").strip().lower() == "true"
        except PainterError:
            opn = False
        try:
            ed = bool(rp.sheet("__import__('substance_painter.project', "
                               "fromlist=['x']).is_in_edition_state()"))
        except PainterError:
            ed = False
        if opn and ed:
            ready = True
            break
        print("   waiting for project (open=%s edition=%s, %ds)"
              % (opn, ed, int(time.time() - t0)))
        time.sleep(5)
    if not ready:
        raise SystemExit("no open project in edition state after 300s - "
                         "open the sheep in Painter first")
    print("project ready.")

    if not args.skip_bake:
        print(">> bake configure:", rp.exec_js(BAKE_CONFIGURE).strip()[:200])
        print(">> bake trigger:", rp.exec_js(BAKE_TRIGGER).strip()[:200])
        t0 = time.time()
        while time.time() - t0 < 1500:
            busy = rp.exec_js("alg.project.isBusy()").strip()
            print("   busy=%s (%ds)" % (busy, int(time.time() - t0)))
            if busy != "true":
                break
            time.sleep(5)

    rep_path = os.path.join(HERE, "out", "painter_report.json")
    if os.path.isfile(rep_path):
        os.remove(rep_path)

    run_file_run(
        ("import json\n"
         "rep = G['run_job'](composer_json=r'%s', exports_dir=r'%s', "
         "project_path=r'%s', log_path=r'%s')\n"
         "raise Exception('COMPOSER_REPORT:' + json.dumps(rep, default=str))"
         % (args.composer, args.exports, args.project, args.log)),
        "composer job (blocking; watch %s)" % args.log)

    if os.path.isfile(rep_path):
        rep = json.load(open(rep_path, encoding="utf-8"))
        print(json.dumps(rep, indent=2)[:4000])
        print("REPORT:", rep_path)
    else:
        print("!! no report file - check the log")


if __name__ == "__main__":
    main()
